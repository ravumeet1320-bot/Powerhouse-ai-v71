def _alert_priority(candidate: dict) -> tuple[Optional[str], Optional[str]]:
    """Map a discovery state to an attention priority without implying profit odds."""
    stage = str(candidate.get("stage") or "DISCOVERY").upper()
    big = str(candidate.get("big_move_state") or "WATCH").upper()
    move_class = str(candidate.get("move_class") or "MICRO MOVE").upper()
    score = _f(candidate.get("score"), 0.0) or 0.0
    if stage in ("TRIGGER READY", "HERO", "ENTRY ACTIVE") or big in ("BREAK IMMINENT", "MOVE ACTIVE"):
        return "P0", "ACTIONABLE_STATE"
    if stage in ("ARMING", "TRIGGER NEAR") or move_class in ("BIG MOVE", "BREAKOUT MOVE", "REVERSAL MOVE", "SECTOR MOVE", "CIRCUIT MOVE", "EXPIRY GAMMA MOVE"):
        return "P1", "MOVE_PRESSURE"
    if stage in ("BUILDING", "ACCELERATING"):
        return "P2", "EARLY_BUILD"
    if stage == "EARLY CLUE" and score >= 32:
        return "P3", "EARLY_CLUE"
    return None, None


