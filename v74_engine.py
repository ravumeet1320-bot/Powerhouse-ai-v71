def call_journal(limit: int = 100) -> dict:
    rows = []
    storage_error = None
    try:
        with _call_db() as c:
            got = c.execute("SELECT * FROM v74_calls ORDER BY epoch DESC LIMIT ?", (max(1, min(int(limit), 1000)),)).fetchall()
            for r in got:
                x = dict(r)
                try:
                    x["payload"] = json.loads(x.pop("payload_json") or "{}")
                except Exception:
                    x["payload"] = {}
                rows.append(x)
    except Exception as exc:
        storage_error = str(exc)[:180]
    resolved = [r for r in rows if r.get("result") in ("T1 HIT","T2 HIT","T3 HIT","SL HIT","EXPIRED")]
    wins = [r for r in resolved if str(r.get("result") or "").startswith("T")]
    sls = [r for r in resolved if r.get("result") == "SL HIT"]
    def window_stats(n: int) -> dict:
        sample = resolved[:n]
        if not sample:
            return {"sample_size":0,"target_hit_pct":None,"sl_hit_pct":None,"median_mfe_pct":None,"median_mae_pct":None,"average_rr_t1":None}
        target = [r for r in sample if str(r.get("result") or "").startswith("T")]
        stop = [r for r in sample if r.get("result") == "SL HIT"]
        mfes=[_f(r.get("max_favorable_pct"),0.0) or 0.0 for r in sample]
        maes=[_f(r.get("max_adverse_pct"),0.0) or 0.0 for r in sample]
        rrs=[_f(r.get("rr_t1")) for r in sample if _f(r.get("rr_t1")) is not None]
        return {"sample_size":len(sample),"target_hit_pct":round(100*len(target)/len(sample),1),"sl_hit_pct":round(100*len(stop)/len(sample),1),"median_mfe_pct":round(statistics.median(mfes),2),"median_mae_pct":round(statistics.median(maes),2),"average_rr_t1":round(statistics.fmean(rrs),2) if rrs else None}
    return {
        "version": VERSION, "rows": rows, "resolved": len(resolved), "target_hits": len(wins), "sl_hits": len(sls),
        "last20": window_stats(20), "last50": window_stats(50), "last100": window_stats(100),
        "storage": {"path": str(V74_DB_PATH), "error": storage_error, "deploy_durable_requires_persistent_disk": True},
        "accuracy_policy": "Observed resolved model calls only. Statistics are historical observations, not guarantees of future accuracy.",
        "read_only": True,
    }


def shadow_comparator(candidates: List[dict], v73: dict) -> dict:
    """Same-snapshot V74-vs-V73/V72 stage comparator; not an outcome forecast."""
    v73_rows = (((v73.get("base_v72") or {}).get("pre_move_rows")) or [])
    m73 = {str(x.get("symbol") or "").upper(): x for x in v73_rows if x.get("symbol")}
    rank = {x:i for i,x in enumerate(LIFECYCLE)}
    aliases = {"SCANNING":"DISCOVERY","WATCH":"EARLY CLUE","EARLY MOVER":"EARLY CLUE","HERO READY":"HERO","HERO ACTIVE":"ENTRY ACTIVE"}
    ahead = same = behind = 0
    rows=[]
    for c in candidates:
        sym=str(c.get("symbol") or "")
        old=m73.get(sym) or {}
        s74=str(c.get("stage") or "DISCOVERY").upper()
        s73=str(old.get("pre_move_stage") or old.get("stage") or "SCANNING").upper()
        s73=aliases.get(s73,s73)
        d=rank.get(s74,0)-rank.get(s73,0)
        if d>0: ahead+=1
        elif d<0: behind+=1
        else: same+=1
        if abs(d)>=1:
            rows.append({"symbol":sym,"v74_stage":s74,"v73_stage":s73,"stage_delta":d,"v74_score":c.get("score"),"v73_score":old.get("pre_move_score") or old.get("score")})
    summary={"epoch":time.time(),"v74_ahead":ahead,"same":same,"v74_behind":behind,"compared":ahead+same+behind}
    with _LOCK:
        _SHADOW_HISTORY.append(summary)
    rows.sort(key=lambda x:abs(int(x.get("stage_delta") or 0)),reverse=True)
    return {**summary,"largest_differences":rows[:30],"policy":"Stage comparison on the same snapshot. It does not by itself prove better trading outcomes.","read_only":True}


def hot_lane_candidates(candidates: List[dict], limit: int = 30) -> List[dict]:
    rank={x:i for i,x in enumerate(LIFECYCLE)}
    out=[]
    for c in candidates:
        price=_scout(c,"price")
        vel=(price.get("velocity") or {})
        burst=max([abs(_f(vel.get(k),0.0) or 0.0) for k in ("15s","30s","60s")],default=0.0)
        if rank.get(str(c.get("stage") or "DISCOVERY"),0)>=rank.get("ARMING",4) or burst>=0.18 or (_f(c.get("score"),0) or 0)>=67:
            out.append({**c,"hot_burst_pct":round(burst,3)})
    out.sort(key=lambda x:(rank.get(str(x.get("stage") or "DISCOVERY"),0),_f(x.get("score"),0) or 0,_f(x.get("hot_burst_pct"),0) or 0),reverse=True)
    return out[:max(1,min(int(limit),100))]



def _scout(candidate: dict, name: str) -> dict:
    return (((candidate.get("scout_pack") or {}).get("scouts") or {}).get(name) or {})


def _scout_score(candidate: dict, name: str) -> float:
    val = _f(_scout(candidate, name).get("score"))
    return val if val is not None else -1.0


def _workspace_payload(
    snapshot: dict,
    v73: dict,
    candidates: List[dict],
    coverage: dict,
    session: dict,
    alerts: dict,
    misses: dict,
    performance: dict,
    shadow: Optional[dict] = None,
    journal: Optional[dict] = None,
) -> dict:
    """Evidence-specific datasets for the compact nine-workspace UI."""
    rank = {x: i for i, x in enumerate(LIFECYCLE)}
    gainers = sorted((x for x in candidates if (_f(x.get("change_pct"), 0) or 0) > 0), key=lambda x: _f(x.get("change_pct"), 0) or 0, reverse=True)[:30]
    losers = sorted((x for x in candidates if (_f(x.get("change_pct"), 0) or 0) < 0), key=lambda x: _f(x.get("change_pct"), 0) or 0)[:30]
    fast = sorted(candidates, key=lambda x: (_scout_score(x, "price"), abs(_f(x.get("change_pct"), 0) or 0)), reverse=True)[:40]
    hot = hot_lane_candidates(candidates, 40)
    adv = sum(1 for x in candidates if (_f(x.get("change_pct"), 0) or 0) > 0)
    dec = sum(1 for x in candidates if (_f(x.get("change_pct"), 0) or 0) < 0)
    flat = max(0, len(candidates) - adv - dec)
    changes = [_f(x.get("change_pct")) for x in candidates if _f(x.get("change_pct")) is not None]

    sector_groups: Dict[str, List[dict]] = defaultdict(list)
    for x in candidates:
        sector = str(x.get("sector") or "").strip()
        if sector and sector.upper() not in ("N/A", "NA", "NONE", "UNKNOWN"):
            sector_groups[sector].append(x)
    sectors = []
    for sector, members in sector_groups.items():
        ch = [_f(x.get("change_pct"), 0) or 0 for x in members]
        scores = [_f(x.get("score"), 0) or 0 for x in members]
        leader = max(members, key=lambda x: (_f(x.get("score"), 0) or 0, _f(x.get("change_pct"), 0) or 0))
        sectors.append({
            "sector": sector, "symbols": len(members),
            "advancers": sum(1 for v in ch if v > 0), "decliners": sum(1 for v in ch if v < 0),
            "avg_change_pct": round(statistics.fmean(ch), 3) if ch else None,
            "avg_opportunity_score": round(statistics.fmean(scores), 1) if scores else None,
            "leader": leader.get("symbol"), "leader_score": leader.get("score"),
            "leader_change_pct": leader.get("change_pct"),
            "ignition_count": sum(1 for x in members if bool(_scout(x, "sector").get("ignition"))),
        })
    sectors.sort(key=lambda x: (x.get("avg_opportunity_score") or 0, abs(x.get("avg_change_pct") or 0)), reverse=True)

    early = [x for x in candidates if rank.get(str(x.get("stage") or "DISCOVERY"), 0) in (1, 2, 3, 4)]
    trigger = [x for x in candidates if str(x.get("stage") or "") in ("TRIGGER NEAR", "TRIGGER READY", "HERO", "ENTRY ACTIVE")]
    breakouts = [x for x in candidates if x.get("move_class") == "BREAKOUT MOVE" or bool(_scout(x, "pattern").get("breakout"))]
    reversals = [x for x in candidates if x.get("move_class") == "REVERSAL MOVE" or bool(_scout(x, "pattern").get("reversal"))]
    reentry = [x for x in candidates if x.get("second_chance")]

    derivatives, flow, technical = [], [], []
    for x in candidates:
        oi, opt = _scout(x, "oi"), _scout(x, "options")
        vol, order, pattern = _scout(x, "volume"), _scout(x, "order_flow"), _scout(x, "pattern")
        if oi.get("status") == "READY" or opt.get("status") == "READY":
            derivatives.append({
                "symbol": x.get("symbol"), "ltp": x.get("ltp"), "change_pct": x.get("change_pct"), "stage": x.get("stage"),
                "oi_score": oi.get("score"), "oi_state": oi.get("state"), "delta_oi_pct": oi.get("delta_oi_pct"), "oi_velocity": oi.get("oi_velocity"),
                "option_score": opt.get("score"), "premium_response": opt.get("premium_response"), "iv": opt.get("iv"), "gamma": opt.get("gamma"),
            })
        if vol.get("status") == "READY" or order.get("status") == "READY":
            flow.append({
                "symbol": x.get("symbol"), "stage": x.get("stage"), "change_pct": x.get("change_pct"),
                "volume_score": vol.get("score"), "rvol": vol.get("rvol"), "volume_state": vol.get("state"),
                "order_flow_score": order.get("score"), "pressure": order.get("pressure"), "spread_pct": order.get("spread_pct"),
                "bias": order.get("bias"), "absorption": order.get("absorption"), "liquidity_vacuum": order.get("liquidity_vacuum"),
            })
        if pattern.get("status") == "READY" or x.get("supply_demand") or x.get("pattern"):
            technical.append({
                "symbol": x.get("symbol"), "stage": x.get("stage"), "change_pct": x.get("change_pct"),
                "pattern": pattern.get("pattern") or x.get("pattern"), "pattern_score": pattern.get("score"),
                "breakout": pattern.get("breakout"), "reversal": pattern.get("reversal"), "compression": pattern.get("compression"),
                "supply_demand": x.get("supply_demand"), "break_pressure": x.get("break_pressure"),
            })
    derivatives.sort(key=lambda x: max((_f(x.get("oi_score")) if _f(x.get("oi_score")) is not None else -1), (_f(x.get("option_score")) if _f(x.get("option_score")) is not None else -1)), reverse=True)
    flow.sort(key=lambda x: max((_f(x.get("volume_score")) if _f(x.get("volume_score")) is not None else -1), (_f(x.get("order_flow_score")) if _f(x.get("order_flow_score")) is not None else -1)), reverse=True)
    technical.sort(key=lambda x: (_f(x.get("pattern_score")) if _f(x.get("pattern_score")) is not None else -1), reverse=True)

    market = {
        "breadth": {"advancers": adv, "decliners": dec, "unchanged": flat, "advance_decline_ratio": round(adv / dec, 3) if dec else ("ADVANCE_ONLY" if adv else None), "average_change_pct": round(statistics.fmean(changes), 3) if changes else None},
        "active_underlying": snapshot.get("active_underlying"), "spot": snapshot.get("spot"),
        "index_brain": snapshot.get("index_brain"), "gainers": gainers, "losers": losers, "fast_movers": fast,
        "sectors": sectors, "sector_count": len(sectors),
    }
    opportunities = {
        "hot_lane": hot,
        "early_build": sorted(early, key=lambda x: _f(x.get("score"), 0) or 0, reverse=True)[:80],
        "trigger_queue": trigger[:60], "breakouts": breakouts[:40], "reversals": reversals[:40],
        "circuits": ((v73.get("circuit_hunter") or {}).get("candidates") or [])[:40],
    }
    calls = {
        "hero_ready": [x for x in candidates if str(x.get("stage") or "") in ("TRIGGER READY", "HERO", "ENTRY ACTIVE")][:40],
        "reentry": reentry[:60], "supply_demand": [x for x in candidates if x.get("supply_demand")][:50],
        "journal_stats": journal or {},
        "policy": "CALL ENGINE is stricter than discovery. WAIT and DO NOT CHASE are valid outputs; broker orders remain disabled.",
    }
    flow_technical = {"flow": flow[:100], "technical": technical[:100], "chart": "verified candle endpoint"}
    journal_audit = {"miss_killer": misses, "performance": performance, "replay": "durable V72/V73 timeline", "shadow": shadow or {}, "call_journal": journal or {}}
    payload = {
        "market": market,
        "opportunities": opportunities,
        "calls": calls,
        "derivatives": {"rows": derivatives[:100], "expiry_mode": bool(session.get("expiry_mode")), "session_brain": session, "option_chain": "verified provider endpoint"},
        "flow-technical": flow_technical,
        "alerts": alerts,
        "journal-audit": journal_audit,
        "system": {"coverage": coverage, "data_quality": v73.get("data_quality"), "session_brain": session},
    }
    # Compatibility aliases for older V74 UI/API consumers.
    payload["sectors"] = {"rows": sectors, "count": len(sectors)}
    payload["execution"] = calls
    payload["flow"] = {"rows": flow[:100]}
    payload["technical"] = {"rows": technical[:100], "chart": "verified candle endpoint"}
    payload["audit"] = journal_audit
    return payload

