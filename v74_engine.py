def alert_engine_v74(candidates: List[dict], legacy_alerts: Optional[dict] = None) -> dict:
    """State-transition alerts generated on every server-side scan.

    Discovery alerts are broader than Hero qualification so a candidate can be surfaced
    early without pretending it is already a trade. Repeated identical states are
    deduplicated; promotions and important move-state changes are emitted immediately.
    """
    now = time.time()
    rank = {x: i for i, x in enumerate(LIFECYCLE)}
    fresh: List[dict] = []
    for c in candidates:
        sym = str(c.get("symbol") or "").upper()
        if not sym:
            continue
        stage = str(c.get("stage") or "DISCOVERY").upper()
        stage_rank = rank.get(stage, 0)
        big = str(c.get("big_move_state") or "WATCH").upper()
        priority, kind = _alert_priority(c)
        with _LOCK:
            prev = dict(_V74_ALERT_STAGE.get(sym) or {})
        prev_rank = int(prev.get("stage_rank") or 0)
        prev_big = str(prev.get("big_move_state") or "WATCH").upper()
        prev_meaningful = bool(prev.get("meaningful_move"))
        meaningful = bool(c.get("meaningful_move"))
        reason = None
        if priority:
            if not prev:
                # Do not dump hundreds of low-priority alerts on process warm-up.
                # Strong states present at startup are still surfaced.
                if priority in ("P0", "P1"):
                    reason = "scanner warm-start found high-priority state"
            elif stage_rank > prev_rank:
                reason = f"lifecycle promoted {prev.get('stage') or 'DISCOVERY'} → {stage}"
            elif big != prev_big and big in ("EARLY BUILD", "PRESSURE RISING", "BREAK IMMINENT", "MOVE ACTIVE"):
                reason = f"big-move state changed {prev_big} → {big}"
            elif meaningful and not prev_meaningful:
                reason = f"meaningful move detected: {c.get('move_class')}"
            elif (c.get("second_chance") or []) and not (prev.get("second_chance") or []):
                reason = "second-chance/re-entry evidence appeared"
        if reason and priority and kind:
            ttl = 15 if priority == "P0" else 25 if priority == "P1" else 45 if priority == "P2" else 75
            item = _emit_v74_alert(priority, kind, c, reason, ttl)
            if item:
                fresh.append(item)
        with _LOCK:
            _V74_ALERT_STAGE[sym] = {
                "stage": stage,
                "stage_rank": stage_rank,
                "big_move_state": big,
                "meaningful_move": meaningful,
                "second_chance": list(c.get("second_chance") or []),
                "last_seen": now,
            }
    # Keep state bounded to names observed within a trading-session scale window.
    with _LOCK:
        for sym in list(_V74_ALERT_STAGE):
            if now - float((_V74_ALERT_STAGE.get(sym) or {}).get("last_seen") or now) > 86400:
                _V74_ALERT_STAGE.pop(sym, None)
        own = list(_V74_ALERT_HISTORY)
    legacy_items = list((legacy_alerts or {}).get("items") or [])
    items = sorted((own + legacy_items), key=lambda x: float(x.get("epoch") or 0), reverse=True)[:300]
    counts = {p: sum(1 for x in items if x.get("priority") == p) for p in ("P0", "P1", "P2", "P3")}
    return {
        "status": "READY",
        "version": VERSION,
        "new": fresh,
        "items": items,
        "counts": counts,
        "server_side_continuous": True,
        "delivery": {
            "in_app": True,
            "browser_notification_when_enabled": True,
            "closed_app_web_push": False,
        },
        "policy": "P0/P1 are urgent attention states, P2/P3 are earlier discovery states. Priorities are not profit probabilities.",
    }


